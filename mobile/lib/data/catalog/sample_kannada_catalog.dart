  static Song _buildSong({
    required String id,
    required String titleEn,
    required String titleKn,
    required String singer,
    required String composer,
    required String lyricist,
    required String movieOrAlbum,
    required int year,
    required KannadaCategory category,
    required String labelName,
    required int popularityScore,
    required String sampleEnLyric,
    required String sampleKnLyric,
  }) {
    final isrcYear = (year % 100).toString().padLeft(2, '0');
    final origStream = originalAudioStreams[id] ??
        'https://audio-ssl.itunes.apple.com/itunes-assets/AudioPreview221/v4/cf/06/bf/cf06bfe2-fe7c-8dc6-c0d5-22d32fc56427/mzaf_33530269438396467.plus.aac.p.m4a';
    return Song(
      id: id,
      titleKn: titleKn,
      titleEn: titleEn,
      artist: singer.split(',').first.trim(),
      singer: singer,
      composer: composer,
      lyricist: lyricist,
      movieOrAlbum: movieOrAlbum,
      year: year,
      category: category,
      genre: '${category.labelEn} ($year)',
      durationSeconds: 240 + ((year * 7) % 80),
      coverArtUrl: 'https://cdn.raaga.karnataka.in/covers/$id.jpg',
      language: 'Kannada',
      streams: AdaptiveStreams(
        low64kUrl: origStream.replaceAll('_320.mp4', '_96.mp4'),
        medium128kUrl: origStream.replaceAll('_320.mp4', '_160.mp4'),
        high320kUrl: origStream,
      ),
      syncedLyrics: [
        SyncedLyricLine(
          timestamp: const Duration(seconds: 0),
          kannadaLine: sampleKnLyric,
          englishTransliteration: sampleEnLyric,
        ),
        SyncedLyricLine(
          timestamp: const Duration(seconds: 8),
          kannadaLine: 'ಗಾಯಕರು: $singer • ಸಂಗೀತ: $composer',
          englishTransliteration: 'Sung by $singer • Music by $composer',
        ),
      ],
      labelName: labelName,
      isrcCode: 'IN-KAN-$isrcYear-$id',
      popularityScore: popularityScore,
    );
  }

